package xcodebuildmcp

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const (
	adapterSubdir     = "xcodebuildmcp"
	mcpJSONName       = "mcp.json"
	sessionYAMLName   = "config.yaml"
	pidMetaName       = "adapter.pid.json"
	logName           = "adapter.log"
	versionName       = "xcodebuildmcp.version"
)

// SessionPaths are ephemeral adapter artifacts under the lease root.
type SessionPaths struct {
	Root         string
	MCPJSON      string
	SessionYAML  string
	PIDMeta      string
	Log          string
	VersionFile  string
}

// AdapterDir returns <leaseRoot>/xcodebuildmcp and related paths.
func AdapterDir(leaseRoot string) SessionPaths {
	root := filepath.Join(leaseRoot, adapterSubdir)
	return SessionPaths{
		Root:        root,
		MCPJSON:     filepath.Join(root, mcpJSONName),
		SessionYAML: filepath.Join(root, sessionYAMLName),
		PIDMeta:     filepath.Join(root, pidMetaName),
		Log:         filepath.Join(root, logName),
		VersionFile: filepath.Join(root, versionName),
	}
}

// MCPServerEntry is the ephemeral Claude/Cursor-compatible MCP server block.
type MCPServerEntry struct {
	Command string            `json:"command"`
	Args    []string          `json:"args"`
	Env     map[string]string `json:"env"`
}

// EphemeralMCPConfig is written under the lease root — never committed.
type EphemeralMCPConfig struct {
	MCPServers map[string]MCPServerEntry `json:"mcpServers"`
}

// WriteEphemeralConfig materializes MCP client JSON + XcodeBuildMCP session YAML
// under the lease adapter directory. UDID appears only in these ephemeral files.
func WriteEphemeralConfig(b Bindings, command string, args []string) (SessionPaths, error) {
	paths := AdapterDir(b.Dirs.Root)
	if err := os.MkdirAll(paths.Root, 0o700); err != nil {
		return SessionPaths{}, fmt.Errorf("xcodebuildmcp: mkdir adapter dir: %w", err)
	}

	env := map[string]string{}
	for k, v := range b.Env {
		env[k] = v
	}

	cfg := EphemeralMCPConfig{
		MCPServers: map[string]MCPServerEntry{
			"XcodeBuildMCP": {
				Command: command,
				Args:    append([]string(nil), args...),
				Env:     env,
			},
		},
	}
	raw, err := json.MarshalIndent(cfg, "", "  ")
	if err != nil {
		return SessionPaths{}, err
	}
	if err := atomicWriteFile(paths.MCPJSON, raw, 0o600); err != nil {
		return SessionPaths{}, err
	}

	yaml := buildSessionYAML(b)
	if err := atomicWriteFile(paths.SessionYAML, []byte(yaml), 0o600); err != nil {
		return SessionPaths{}, err
	}
	return paths, nil
}

func buildSessionYAML(b Bindings) string {
	var sb strings.Builder
	sb.WriteString("# Generated by simurgh — ephemeral per-lease XcodeBuildMCP defaults.\n")
	sb.WriteString("# Do not commit. Paths and UDID are lease-scoped.\n")
	sb.WriteString("sessionDefaults:\n")
	sb.WriteString(fmt.Sprintf("  simulatorId: %q\n", b.UDID))
	sb.WriteString(fmt.Sprintf("  derivedDataPath: %q\n", b.Dirs.DerivedData))
	sb.WriteString("  preferXcodebuild: true\n")
	sb.WriteString("  env:\n")
	sb.WriteString(fmt.Sprintf("    CLANG_MODULE_CACHE_PATH: %q\n", b.Env["CLANG_MODULE_CACHE_PATH"]))
	sb.WriteString(fmt.Sprintf("    SIMURGH_RESULT_BUNDLE_DIR: %q\n", b.Env["SIMURGH_RESULT_BUNDLE_DIR"]))
	sb.WriteString(fmt.Sprintf("    SIMURGH_SWIFTPM_DIR: %q\n", b.Env["SIMURGH_SWIFTPM_DIR"]))
	sb.WriteString("  # Source-packages / destination via tool extraArgs (session schema has no field):\n")
	sb.WriteString(fmt.Sprintf("  # extraArgs: %q\n", b.ExtraArgs))
	return sb.String()
}

func atomicWriteFile(path string, data []byte, mode os.FileMode) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, filepath.Base(path)+".*.tmp")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	ok := false
	defer func() {
		if !ok {
			_ = os.Remove(tmpName)
		}
	}()
	if err := tmp.Chmod(mode); err != nil {
		_ = tmp.Close()
		return err
	}
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmpName, path); err != nil {
		return err
	}
	ok = true
	return nil
}
